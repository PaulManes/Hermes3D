import fs from "node:fs";
import path from "node:path";

const root = path.join("audit", "dependencies");

const read = (name) => {
  try {
    return fs.readFileSync(path.join(root, name), "utf8").trim();
  } catch {
    return "";
  }
};

const readJson = (name, fallback = {}) => {
  try {
    return JSON.parse(read(name) || JSON.stringify(fallback));
  } catch {
    return fallback;
  }
};

const parseCodes = (text) =>
  Object.fromEntries(
    text
      .split(/\r?\n/)
      .filter(Boolean)
      .map((line) => {
        const index = line.indexOf("=");
        return index === -1
          ? [line, ""]
          : [line.slice(0, index), line.slice(index + 1)];
      }),
  );

const numericMajor = (value) => {
  const match = String(value ?? "").match(/(\d+)/);
  return match ? Number(match[1]) : null;
};

const auditSummary = (value) => value?.metadata?.vulnerabilities ?? {};
const packageJson = JSON.parse(fs.readFileSync("package.json", "utf8"));
const checks = parseCodes(read("verification-exit-codes.txt"));
const auditCodes = parseCodes(read("audit-exit-codes.txt"));
const allAudit = auditSummary(readJson("npm-audit-all.json"));
const productionAudit = auditSummary(readJson("npm-audit-production.json"));
const packagesWithScripts = readJson("packages-with-scripts.json", []);
const outdatedBefore = readJson("outdated-before.json", {});
const scriptCount = Array.isArray(packagesWithScripts)
  ? packagesWithScripts.length
  : 0;

const result = (code) => (String(code) === "0" ? "PASS" : "FAIL");
const dependencyRows = [
  ...Object.entries(packageJson.dependencies ?? {}).map(
    ([name, version]) => `| ${name} | ${version} | runtime |`,
  ),
  ...Object.entries(packageJson.devDependencies ?? {}).map(
    ([name, version]) => `| ${name} | ${version} | development |`,
  ),
].sort();

const heldMajorRows = Object.entries(outdatedBefore)
  .filter(([, value]) => {
    const currentMajor = numericMajor(value?.current);
    const latestMajor = numericMajor(value?.latest);
    return (
      currentMajor !== null &&
      latestMajor !== null &&
      latestMajor > currentMajor
    );
  })
  .map(
    ([name, value]) =>
      `| ${name} | ${value.current ?? "unknown"} | ${value.wanted ?? "unknown"} | ${value.latest ?? "unknown"} |`,
  )
  .sort();

const report = `# Dependency Refresh Report

Generated by the isolated GitHub-hosted macOS dependency refresh. No commands in this report were run on the developer workstation.

## Update policy

This pass updates every direct dependency to the newest patch or minor release available within its current major version, regenerates the lockfile with lifecycle scripts disabled, and rejects invalid peer dependency trees. Major-version upgrades are recorded below and held for isolated migrations so a nominally "latest" update cannot silently introduce incompatible toolchains or runtime APIs.

## Toolchain

\`\`\`
${read("toolchain.txt") || "missing"}
\`\`\`

## Verification

| Check | Result | Exit code |
| --- | --- | ---: |
| Peer dependency tree | ${result(checks.peer_tree)} | ${checks.peer_tree ?? "missing"} |
| Lint | ${result(checks.lint)} | ${checks.lint ?? "missing"} |
| Typecheck | ${result(checks.typecheck)} | ${checks.typecheck ?? "missing"} |
| Unit tests | ${result(checks.test)} | ${checks.test ?? "missing"} |
| Production build | ${result(checks.build)} | ${checks.build ?? "missing"} |
| Dev-server smoke test | ${result(checks.smoke)} | ${checks.smoke ?? "missing"} |

## npm audit

| Scope | Critical | High | Moderate | Low | Total | Exit code |
| --- | ---: | ---: | ---: | ---: | ---: | ---: |
| All dependencies | ${allAudit.critical ?? 0} | ${allAudit.high ?? 0} | ${allAudit.moderate ?? 0} | ${allAudit.low ?? 0} | ${allAudit.total ?? 0} | ${auditCodes.all ?? "missing"} |
| Production only | ${productionAudit.critical ?? 0} | ${productionAudit.high ?? 0} | ${productionAudit.moderate ?? 0} | ${productionAudit.low ?? 0} | ${productionAudit.total ?? 0} | ${auditCodes.production ?? "missing"} |

## Lifecycle-script surface

The refreshed installation contains **${scriptCount}** packages with install-time lifecycle scripts. The packages were installed with scripts disabled, inventoried from their manifests, and only then rebuilt inside the disposable runner. The complete inventory is in \`packages-with-scripts.json\`.

## Major upgrades held for separate migration

${heldMajorRows.length > 0 ? `| Package | Current | Latest compatible in current range | Latest major |\n| --- | ---: | ---: | ---: |\n${heldMajorRows.join("\n")}` : "No newer major versions were reported by npm."}

## Refreshed direct dependencies

| Package | Requested version | Scope |
| --- | --- | --- |
${dependencyRows.join("\n")}

## Commit policy

The workflow commits \`package.json\`, \`package-lock.json\`, and this report only when both npm audits and every verification gate pass. Failed candidates remain available only in the short-lived audit artifact for diagnosis.

## Raw evidence artifact

The workflow artifact \`hermes3d-dependency-audit\` contains:

- direct dependency drift before the refresh;
- the lifecycle-script inventory;
- full and production-only npm audit JSON;
- the candidate package and lock files plus their patch;
- lifecycle execution, peer-tree, lint, typecheck, test, build, and smoke-test logs;
- the verification and audit exit-code records.
`;

fs.mkdirSync(root, { recursive: true });
fs.writeFileSync(path.join(root, "REPORT.md"), report);
